#!/usr/bin/env python3
"""
make_result_tables.py -- Generate LaTeX result tables from the campaign
CSVs, for Chapter 5 and Appendix C of the thesis.

Output: memoria/chapters/generated_tables.tex with:
  tab:nist-results-full   per-test p-value x condition (rep 1), PASS/FAIL
  tab:nist-summary        tests passed per condition per rep
  tab:entropy-summary     Shannon/autocorr/flatness/zlib per condition
  tab:harvester           harvester validation metrics

TFM -- Mario Garcia Jimenez.
"""
from pathlib import Path
import csv

HERE = Path(__file__).parent
RESULTS = HERE.parents[1] / "results" / "esp32_rng_agosto"
OUT = RESULTS / "tablas_generadas.tex"

CONDS = ["A", "B", "C", "D"]
COND_DESC = {"A": "WiFi+ADC", "B": "WiFi only", "C": "ADC only", "D": "neither"}


def esc(s):
    return str(s).replace("_", r"\_").replace("%", r"\%")


def nist_full_table() -> str:
    f = RESULTS / "nist_results.csv"
    if not f.exists():
        return "% nist_results.csv not found\n"
    # {test: {cond: (p, passed)}} for rep 1
    data, tests = {}, []
    with f.open() as fh:
        for r in csv.DictReader(fh):
            if r["rep"] != "1":
                continue
            data.setdefault(r["test"], {})[r["condition"]] = (
                float(r["p_value"]), r["passed"] == "1")
            if r["test"] not in tests:
                tests.append(r["test"])
    conds = [c for c in CONDS if any(c in data.get(t, {}) for t in tests)]
    out = ["\\begin{table}[htbp]\n\\centering\\small",
           "\\caption{NIST SP 800-22 p-values by operating condition "
           "(rep.\\ 1). Bold = FAIL (p $<$ 0.01).}",
           "\\label{tab:nist-results-full}",
           "\\begin{tabular}{@{}l" + "c" * len(conds) + "@{}}\\toprule",
           "Test & " + " & ".join(conds) + " \\\\",
           "\\midrule"]
    for t in tests:
        cells = []
        for c in conds:
            if c in data.get(t, {}):
                p, ok = data[t][c]
                cells.append(f"{p:.3f}" if ok else f"\\textbf{{{p:.3f}}}")
            else:
                cells.append("--")
        out.append(f"{esc(t)} & " + " & ".join(cells) + " \\\\")
    out += ["\\bottomrule\\end{tabular}\\end{table}\n"]
    return "\n".join(out)


def nist_summary_table() -> str:
    f = RESULTS / "nist_summary.csv"
    if not f.exists():
        return "% nist_summary.csv not found\n"
    rows = list(csv.DictReader(f.open()))
    out = ["\\begin{table}[htbp]\n\\centering\\small",
           "\\caption{Tests passed (out of 15) per condition and "
           "repetition.}",
           "\\label{tab:nist-summary}",
           "\\begin{tabular}{@{}lccc@{}}\\toprule",
           "Condition & Rep & Passed & Total \\\\\\midrule"]
    for r in rows:
        out.append(f"{r['condition']} ({COND_DESC.get(r['condition'],'')}) "
                   f"& {r['rep']} & {r['tests_passed']} & "
                   f"{r['tests_total']} \\\\")
    out += ["\\bottomrule\\end{tabular}\\end{table}\n"]
    return "\n".join(out)


def entropy_table() -> str:
    f = RESULTS / "entropy_summary.csv"
    if not f.exists():
        return "% entropy_summary.csv not found\n"
    rows = list(csv.DictReader(f.open()))
    out = ["\\begin{table}[htbp]\n\\centering\\small",
           "\\caption{Information-theoretic metrics per condition "
           "(rep.\\ 1). Ideal: H=8 bits/byte, autocorr 0, flatness 1, "
           "zlib ratio 1.}",
           "\\label{tab:entropy-summary}",
           "\\begin{tabular}{@{}lccccc@{}}\\toprule",
           "Cond & H [b/byte] & H [b/bit] & max$|$ac$|$ & flatness & "
           "zlib \\\\\\midrule"]
    for r in rows:
        out.append(f"{r['condition']} & {float(r['H_bits_per_byte']):.5f} "
                   f"& {float(r['H_bits_per_bit']):.6f} "
                   f"& {float(r['autocorr_max']):.4f} "
                   f"& {float(r['spectral_flatness']):.4f} "
                   f"& {float(r['zlib_ratio']):.4f} \\\\")
    out += ["\\bottomrule\\end{tabular}\\end{table}\n"]
    return "\n".join(out)


def harvester_table() -> str:
    f = RESULTS / "harvester_validation.csv"
    if not f.exists():
        return "% harvester_validation.csv not found\n"
    out = ["\\begin{table}[htbp]\n\\centering\\small",
           "\\caption{Harvester validation metrics.}",
           "\\label{tab:harvester}",
           "\\begin{tabular}{@{}ll@{}}\\toprule Metric & Value "
           "\\\\\\midrule"]
    with f.open() as fh:
        for r in csv.reader(fh):
            if len(r) == 2 and r[0] != "metric":
                out.append(f"{esc(r[0])} & {esc(r[1])} \\\\")
    out += ["\\bottomrule\\end{tabular}\\end{table}\n"]
    return "\n".join(out)


def main():
    parts = ["% Auto-generated by make_result_tables.py\n",
             nist_full_table(), nist_summary_table(),
             entropy_table(), harvester_table()]
    OUT.write_text("\n".join(parts), encoding="ascii", errors="replace")
    print(f"-> {OUT}")


if __name__ == "__main__":
    main()
